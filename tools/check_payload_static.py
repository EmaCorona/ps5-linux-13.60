#!/usr/bin/env python3
"""Static checks on a built payload and on the shellcode embedded in it.

Answers, from the artifact alone, the questions the release checklist asks:

  * is this a PS5 payload ELF at all (format, class, machine, entry)?
  * does it belong to the manifest version this tree claims?
  * was phase B (the 13.60 post-resume takeover) compiled in or out?
  * are the generated shellcode blobs the ones this tree produced, and are they
    present verbatim in the ELF?
  * is the takeover blob's firmware one we have provenance for?

This is a packaging check, not a runtime check: it never contacts a console and
never claims the payload boots anything.

Exit codes:
    0   every check ran and passed
    1   at least one check failed
    2   unusable input, or a claim this tool refuses to make (no provenance)

Usage:
    check_payload_static.py [--elf PATH] [--manifest PATH]
                            [--shellcode-dir PATH] [--takeover 0|1]
                            [--takeover-fw FW] [--report PATH]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

EM_X86_64 = 62
ET_DYN = 3
ET_EXEC = 2

# The blobs the build produces. `embedded` says whether the payload is expected
# to carry the bytes verbatim: hv_boot.bin is generated by the build but nothing
# in source/ references hv_boot_bin, so it is not part of the payload image.
BLOBS = [
    ("shellcode_0607", "source/shellcode/0607/shellcode_0607", True),
    ("shellcode_hv", "source/shellcode/hv/shellcode_hv", True),
    ("shellcode_kernel", "source/shellcode/kernel/shellcode_kernel", True),
    ("break_hv", "source/shellcode/break_hv/break_hv", True),
    ("hv_boot", "source/shellcode/hv_boot/hv_boot", False),
    ("takeover", "source/shellcode/hv_takeover/takeover", True),
    # Stage-1 #DB trampoline: built and validated every build, staged into the scratch
    # page only when the hook is armed (off by default), so it is not in the image.
    ("db_trampoline", "source/shellcode/db_trampoline/db_trampoline", False),
]

# Firmware provenance for the shared takeover blob. A blob carries one
# firmware's constants and embeds no naming literal, so "which firmware" is only
# answerable from a table like this one. 13.60 is deliberately absent: its
# required hypervisor reference is unknown, so no 13.60 blob can be validated.
TAKEOVER_FW_KNOWN = {1320: {"size": 144}}

# Strings the compiler emits with (or without) phase B. The 13.20 sibling is
# always compiled; the 13.60 one only under PL5_1360_TAKEOVER.
PHASE_B_PRESENT_MARKER = b"13.60: [VERIFY] vmmcall-stub"
PHASE_A_SIBLING_MARKER = b"13.20: [VERIFY] vmmcall-stub"

# Arming the experimental #DB hook is opt-in (Task 13.3). These two strings are
# compiled into the 13.60 code path only with PL5_1360_ARM_HOOK=1, so their
# presence/absence in the artifact is how a regression is detected without a
# console. The 13.20 file has its own self-test strings and is not a marker here.
ARMING_PRESENT_MARKER = b"13.60: arm-late: kh_arm rc"
ARMING_STAGING_MARKER = b"hook NOT installed (arm="


class Checker:
    def __init__(self, elf: Path, manifest: Path, shellcode_dir: Path,
                 takeover: int, takeover_fw: int, report: Path | None,
                 arming: int = 0):
        self.elf = elf
        self.manifest = manifest
        self.shellcode_dir = shellcode_dir
        self.takeover = takeover
        self.takeover_fw = takeover_fw
        self.arming = arming
        self.report = report
        self.data = b""
        self.failures = 0
        self.lines: list[str] = []

    # -- plumbing ---------------------------------------------------------
    def ok(self, good: bool, msg: str) -> None:
        if not good:
            self.failures += 1
        line = f"{'PASS' if good else 'FAIL'} {msg}"
        print(line)
        self.lines.append(line)

    def emit_report(self, sha_elf: str, blobs: list[tuple[str, int, str]]) -> None:
        if self.report is None:
            return
        body = ["# Static payload report", "",
                f"elf: {self.elf}", f"elf_sha256: {sha_elf}",
                f"takeover_expected: {self.takeover}",
                f"takeover_fw_expected: {self.takeover_fw}",
                f"arming_expected: {self.arming}",
                f"result: {'PASS' if self.failures == 0 else 'FAIL'}", "", "blobs:"]
        body += [f"  {name}: {size} bytes sha256={digest}"
                 for name, size, digest in blobs]
        body += ["", "checks:"] + [f"  {l}" for l in self.lines]
        self.report.parent.mkdir(parents=True, exist_ok=True)
        self.report.write_text("\n".join(body) + "\n")

    # -- checks -----------------------------------------------------------
    def check_elf_header(self) -> None:
        d = self.data
        if len(d) < 64 or d[:4] != b"\x7fELF":
            self.ok(False, "elf: magic (not an ELF file)")
            return
        self.ok(True, "elf: magic")
        cls, data_enc = d[4], d[5]
        self.ok(cls == 2, f"elf: 64-bit class (EI_CLASS={cls})")
        self.ok(data_enc == 1, f"elf: little-endian (EI_DATA={data_enc})")
        e_type, e_machine = struct.unpack_from("<HH", d, 16)
        self.ok(e_type in (ET_DYN, ET_EXEC),
                f"elf: type {'DYN' if e_type == ET_DYN else e_type}")
        self.ok(e_machine == EM_X86_64, f"elf: machine x86-64 ({e_machine})")
        entry = struct.unpack_from("<Q", d, 24)[0]
        self.ok(entry != 0, f"elf: entry point non-zero (0x{entry:x})")

    def check_arming(self) -> None:
        """A default build must not be able to arm the experimental hook."""
        present = ARMING_PRESENT_MARKER in self.data
        if self.arming:
            self.ok(present, "arming: compiled IN (build asked for it explicitly)")
        else:
            self.ok(not present,
                    "arming: compiled OUT in this build (no 13.60 arming marker)")
            self.ok(ARMING_STAGING_MARKER in self.data,
                    "arming: the staging-only notice is present")

    def check_manifest(self) -> None:
        src = self.manifest.read_text()
        version = re.search(r'\.version\s*=\s*"([^"]+)"', src)
        app = re.search(r'\.app_name\s*=\s*"([^"]+)"', src)
        if not version or not app:
            self.ok(False, "manifest: .version/.app_name readable")
            return
        v, a = version.group(1).encode(), app.group(1).encode()
        self.ok(v in self.data, f"manifest: version {version.group(1)!r} present in the ELF")
        self.ok(a in self.data, f"manifest: app name {app.group(1)!r} present in the ELF")

    def check_phase_b(self) -> None:
        present = PHASE_B_PRESENT_MARKER in self.data
        if self.takeover:
            self.ok(present, "phase B: compiled IN (13.60 takeover marker present)")
        else:
            self.ok(not present,
                    "phase B: compiled OUT (no 13.60 takeover marker in the ELF)")
        self.ok(PHASE_A_SIBLING_MARKER in self.data,
                "phase A: 13.20 sibling marker present (expected high-FW code)")

    def check_blobs(self) -> list[tuple[str, int, str]]:
        out: list[tuple[str, int, str]] = []
        for name, stem, embedded in BLOBS:
            binp = ROOT / f"{stem}.bin"
            hdrp = ROOT / f"{stem}.h"
            if not binp.is_file():
                self.ok(False, f"blob {name}: {binp.name} missing (run a build)")
                continue
            body = binp.read_bytes()
            digest = hashlib.sha256(body).hexdigest()
            out.append((name, len(body), digest))
            self.ok(len(body) > 0, f"blob {name}: non-empty ({len(body)} bytes)")
            if embedded:
                self.ok(body in self.data,
                        f"blob {name}: embedded verbatim in the ELF")
            else:
                self.ok(body not in self.data,
                        f"blob {name}: generated but not embedded (unused by the payload)")
            if hdrp.is_file():
                m = re.search(rf"{name}_bin_len\s*=\s*(\d+)", hdrp.read_text())
                self.ok(m is not None and int(m.group(1)) == len(body),
                        f"blob {name}: header declares {m.group(1) if m else '?'} = .bin {len(body)}")
            else:
                self.ok(False, f"blob {name}: generated header {hdrp.name} missing")
        return out

    def check_takeover_fw(self, blobs: list[tuple[str, int, str]]) -> bool:
        known = TAKEOVER_FW_KNOWN.get(self.takeover_fw)
        if known is None:
            print(f"REFUSE {self.takeover_fw}: no provenance for a takeover blob of this "
                  f"firmware; refusing to validate (known: "
                  f"{sorted(TAKEOVER_FW_KNOWN)})")
            return False
        size = next((s for n, s, _ in blobs if n == "takeover"), None)
        self.ok(size == known["size"],
                f"takeover fw {self.takeover_fw}: blob is {size} bytes (expected {known['size']})")
        return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--elf", default=str(ROOT / "bin/pLinux5-NG.elf"))
    ap.add_argument("--manifest", default=str(ROOT / "source/manifest/manifest.c"))
    ap.add_argument("--shellcode-dir", default=str(ROOT / "source/shellcode"))
    ap.add_argument("--takeover", type=int, choices=(0, 1), default=0)
    ap.add_argument("--arming", type=int, choices=(0, 1), default=0,
                    help="was this build made with PL5_1360_ARM_HOOK=1?")
    ap.add_argument("--takeover-fw", type=int, default=1320)
    ap.add_argument("--report", default=None)
    args = ap.parse_args()

    elf = Path(args.elf)
    if not elf.is_file():
        print(f"REFUSE {elf}: payload ELF not found (build first)", file=sys.stderr)
        return 2
    manifest = Path(args.manifest)
    if not manifest.is_file():
        print(f"REFUSE {manifest}: manifest source not found", file=sys.stderr)
        return 2

    data = elf.read_bytes()
    if len(data) < 64:
        print(f"REFUSE {elf}: too small to be an ELF ({len(data)} bytes)", file=sys.stderr)
        return 2

    c = Checker(elf, manifest, Path(args.shellcode_dir), args.takeover,
                args.takeover_fw, Path(args.report) if args.report else None,
                args.arming)
    c.data = data
    c.check_elf_header()
    c.check_manifest()
    c.check_phase_b()
    c.check_arming()
    blobs = c.check_blobs()
    provenance_ok = c.check_takeover_fw(blobs)
    c.emit_report(hashlib.sha256(data).hexdigest(), blobs)

    if not provenance_ok:
        print(f"\n{c.failures} check(s) failed; provenance for the requested firmware "
              f"is unavailable, so the artifact is not validated")
        return 2
    if c.failures:
        print(f"\n{c.failures} check(s) failed")
        return 1
    print("\nall static checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
